// 코레일 공개 KTX 시간표 → 확장에 포함하는 시간표. 실행 중 브라우저·API 키를 쓰지 않는다.
// node tools/import-ktx-timetable.mjs [xlsx 파일] [--basis YYYY-MM-DD] [--source 공식 XLSX 주소]
// 파일을 생략하면 공식 게시판에서 가장 최근 시행표를 찾는다.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { readKorailTimetable } from '../src/ktxtimetable.js';

const BOARD = 'https://www.korail.com/com/userBoard.do?mode=list&schBcid=ticketTable';
const args = process.argv.slice(2);
const option = (key) => { const i = args.indexOf(key); return i < 0 ? '' : args[i + 1]; };
const file = args[0] && !args[0].startsWith('--') ? args[0] : '';
async function get(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`코레일 시간표 응답: ${response.status}`);
  return response;
}
let basis = option('--basis'), source = option('--source');
if (!file) {
  const { boardList } = await (await get(BOARD)).json();
  const entries = boardList.map((item) => ({ item, match: /^KTX 시간표\((\d{4})\.\s*(\d{1,2})\.\s*(\d{1,2})\./.exec(item.bdTitle) })).filter((entry) => entry.match);
  const dates = entries.map(({ item, match }) => ({ item, basis: `${match[1]}-${match[2].padStart(2, '0')}-${match[3].padStart(2, '0')}` })).sort((a, b) => b.basis.localeCompare(a.basis));
  if (!dates.length) throw new Error('코레일 게시판에서 KTX 시간표를 찾지 못했습니다.');
  basis = dates[0].basis;
  const path = dates[0].item.fileId?.find((name) => /^jfile\/[\w/]+\.xlsx$/.test(name));
  if (!path) throw new Error('코레일 시간표 첨부 경로가 올바르지 않습니다.');
  source = `https://www.korail.com/file/cubedata/COMMON/${path}`;
}
if (!/^\d{4}-\d{2}-\d{2}$/.test(basis) || !/^https:\/\/www\.korail\.com\/file\/cubedata\/COMMON\/jfile\/[\w/]+\.xlsx$/.test(source)) throw new Error('공식 XLSX 주소와 시행일을 확인해 주세요.');
const bytes = file ? await fs.readFile(file) : new Uint8Array(await (await get(source)).arrayBuffer());
const trains = await readKorailTimetable(bytes);
if (trains.length < 300) throw new Error(`시간표 열차 수가 예상보다 적습니다: ${trains.length}`);
const data = { basis, source, board: BOARD, sha256: createHash('sha256').update(bytes).digest('hex'), trains };
const output = `// Generated by tools/import-ktx-timetable.mjs from the official Korail workbook.\nexport const KTX_TIMETABLE = ${JSON.stringify(data)};\n`;
await fs.writeFile(new URL('../src/ktxtimes.js', import.meta.url), output);
console.log(`KTX 시간표 ${basis}: ${trains.length}편 · ${Buffer.byteLength(output)} bytes`);
